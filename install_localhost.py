def backup(path: Path) -> Optional[Path]:
    """Copy path to path.wasql-bak (once) so the original is recoverable."""
    if not path.is_file():
        return None
    bak = path.with_suffix(path.suffix + ".wasql-bak")
    if not bak.exists() and not DRY_RUN:
        shutil.copy2(path, bak)
        debug(f"backed up {path} -> {bak.name}")
    return bak


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def write_text(path: Path, text: str, mode: Optional[int] = None):
    """Write text with LF endings (a stray CR breaks apache/my.cnf parsing)."""
    if DRY_RUN:
        info(f"{C.DIM}[dry-run] write {path} ({len(text)} bytes){C.OFF}")
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    if mode is not None and not IS_WIN:
        try:
            os.chmod(path, mode)
        except OSError as e:
            debug(f"chmod {path}: {e}")


def replace_block(text: str, block: str) -> str:
    """Insert or replace the sentinel-delimited WaSQL block in a config file."""
    payload = f"{SENTINEL_BEGIN}\n{block.strip()}\n{SENTINEL_END}\n"
    pattern = re.compile(re.escape(SENTINEL_BEGIN) + r".*?" +
                         re.escape(SENTINEL_END) + r"\n?", re.S)
    if pattern.search(text):
        return pattern.sub(payload, text)
    if text and not text.endswith("\n"):
        text += "\n"
    return text + "\n" + payload


def ensure_dir(path: Path, writable: bool = False, owner: Optional[str] = None):
    if DRY_RUN:
        info(f"{C.DIM}[dry-run] mkdir {path}{C.OFF}")
        return
    path.mkdir(parents=True, exist_ok=True)
    if writable and not IS_WIN:
        try:
            os.chmod(path, 0o777)
        except OSError as e:
            debug(f"chmod 777 {path}: {e}")
        if owner:
            run(["chown", "-R", f"{owner}:{owner}", str(path)], quiet=True)


def ensure_traversable(path: Path):
    """Give the web server o+x on every parent dir so it can reach the repo."""
    if IS_WIN:
        return
    p = path.resolve()
    parents = list(p.parents)[:-1] + [p]
    for d in parents:
        try:
            mode = d.stat().st_mode & 0o777
        except OSError:
            continue
        if not mode & 0o001:
            debug(f"chmod o+x {d}")
            if not DRY_RUN:
                try:
                    os.chmod(d, mode | 0o001)
                except OSError as e:
                    warn(f"could not chmod o+x {d} ({e}); apache may get 403s")


def download(url: str, dest: Path, label: str = "") -> Path:
    if DRY_RUN:
        info(f"{C.DIM}[dry-run] download {url}{C.OFF}")
        return dest
    info(f"downloading {label or url}")
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (compatible; wasql-installer)"})
    dest.parent.mkdir(parents=True, exist_ok=True)
    with urllib.request.urlopen(req, timeout=180) as resp, open(dest, "wb") as fh:
        total = int(resp.headers.get("Content-Length") or 0)
        done = 0
        while True:
            chunk = resp.read(262144)
            if not chunk:
                break
            fh.write(chunk)
            done += len(chunk)
            if total and sys.stdout.isatty():
                pct = done * 100 // total
                print(f"\r    {done//1048576}/{total//1048576} MB ({pct}%)",
                      end="", flush=True)
    if sys.stdout.isatty() and total:
        print()
    return dest


def http_get(url: str, timeout: int = 30) -> tuple[int, str]:
    req = urllib.request.Request(url, headers={"User-Agent": "wasql-installer"})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return r.status, r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode("utf-8", "replace")
    except Exception as e:
        return 0, str(e)


