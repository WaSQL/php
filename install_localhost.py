class LinuxStack(Stack):
    label = "linux"

    def __init__(self, s: Settings):
        super().__init__(s)
        self.pm = self._detect_pm()
        self.profile = LINUX_PROFILES.get(self.pm, {})
        self.distro = self._distro_id()

    @staticmethod
    def _detect_pm() -> str:
        for pm in ("apt-get", "dnf", "yum", "pacman", "zypper"):
            if which(pm):
                return {"apt-get": "apt", "yum": "dnf"}.get(pm, pm)
        return ""

    @staticmethod
    def _distro_id() -> str:
        txt = read_text(Path("/etc/os-release"))
        m = re.search(r"^ID=\"?([\w.-]+)", txt, re.M)
        return m.group(1) if m else "linux"

    # -- discovery ----------------------------------------------------------
    def detect(self):
        deb = self.pm == "apt" or Path("/etc/apache2/apache2.conf").is_file()
        suse = self.pm == "zypper"
        a = self.apache
        a.binary = which("apache2", "httpd")
        a.ctl = which("apache2ctl", "apachectl")
        a.service = self.profile.get("apache_service") or ("apache2" if deb else "httpd")
        a.user = a.group = self.profile.get("apache_user", "www-data")
        if deb:
            a.conf = first_existing("/etc/apache2/apache2.conf")
            a.conf_dir = first_existing("/etc/apache2/conf-available")
            a.ports_conf = first_existing("/etc/apache2/ports.conf")
            a.modules_dir = first_existing("/usr/lib/apache2/modules")
            a.debian_site = True
            a.include_via_conf = False
        elif suse:
            a.conf = first_existing("/etc/apache2/httpd.conf")
            a.conf_dir = first_existing("/etc/apache2/vhosts.d")
            a.ports_conf = first_existing("/etc/apache2/listen.conf")
            a.modules_dir = first_existing("/usr/lib64/apache2", "/usr/lib/apache2")
            a.include_via_conf = False
        else:
            a.conf = first_existing("/etc/httpd/conf/httpd.conf")
            a.conf_dir = first_existing("/etc/httpd/conf.d")
            a.modules_dir = first_existing("/etc/httpd/modules", "/usr/lib64/httpd/modules")
            a.include_via_conf = False
        p = self.php
        p.binary = which("php")
        if p.binary:
            r = run([str(p.binary), "-r", "echo PHP_VERSION;"], quiet=True,
                    allow_dry=False)
            p.version = r.out.strip()
            i = run([str(p.binary), "-i"], quiet=True, allow_dry=False)
            m = re.search(r"Loaded Configuration File => (\S+)", i.out)
            if m and m.group(1) != "(none)":
                p.ini = Path(m.group(1))
        branch = ".".join(p.version.split(".")[:2]) if p.version else "*"
        p.ini_dirs = [Path(d) for d in
                      glob.glob(f"/etc/php/{branch}/apache2/conf.d") +
                      glob.glob(f"/etc/php/{branch}/cli/conf.d") +
                      glob.glob(f"/etc/php/{branch}/fpm/conf.d") +
                      glob.glob("/etc/php.d") +
                      glob.glob("/etc/php/conf.d") +
                      glob.glob("/etc/php8/conf.d") +
                      glob.glob("/etc/php8/apache2/conf.d") +
                      glob.glob("/etc/php8/fastcgi/conf.d")
                      if Path(d).is_dir()]
        p.apache_module = first_existing(
            "/usr/lib/apache2/modules/libphp*.so",
            "/usr/lib64/httpd/modules/libphp*.so",
            "/usr/lib/httpd/modules/libphp*.so",
        )
        if self.profile.get("php_mode") == "fpm" or (
                not p.apache_module and which("php-fpm")):
            p.fpm_service = "php-fpm" if which("php-fpm") or \
                Path("/usr/sbin/php-fpm").exists() else None
            if not p.fpm_service:
                svc = first_existing("/lib/systemd/system/php*-fpm.service",
                                     "/usr/lib/systemd/system/php*-fpm.service")
                if svc:
                    p.fpm_service = svc.stem
        m = self.mysql
        m.client = which("mysql", "mariadb")
        m.server_bin = which("mysqld", "mariadbd")
        m.service = self._mysql_service()
        m.conf_dir = first_existing("/etc/mysql/conf.d", "/etc/my.cnf.d",
                                    "/etc/mysql/mysql.conf.d")
        m.conf_file = first_existing("/etc/my.cnf")

    @staticmethod
    def _mysql_service() -> Optional[str]:
        for svc in ("mysql", "mysqld", "mariadb"):
            r = run(["systemctl", "list-unit-files", f"{svc}.service"],
                    quiet=True, allow_dry=False)
            if r.good and f"{svc}.service" in r.out:
                return svc
        return None

    # -- install ------------------------------------------------------------
    def _available(self, pkgs: list[str]) -> list[str]:
        """Filter to packages this distro actually ships (names vary a lot)."""
        if self.pm == "apt":
            out = []
            for p in pkgs:
                r = run(["apt-cache", "policy", p], quiet=True, allow_dry=False)
                if r.good and "Candidate:" in r.out and "(none)" not in r.out:
                    out.append(p)
                else:
                    debug(f"skip unavailable package {p}")
            return out
        return pkgs  # dnf(strict=0)/pacman --needed/zypper tolerate extras

    def _install(self, pkgs: list[str], label: str) -> bool:
        pkgs = self._available(pkgs)
        if not pkgs:
            return False
        info(f"{label}: {' '.join(pkgs)}")
        env = {"DEBIAN_FRONTEND": "noninteractive"} if self.pm == "apt" else None
        r = run(self.profile["install"] + pkgs, timeout=3600, env=env)
        if not r.good:
            warn(f"package install returned {r.code} for {label}: "
                 f"{r.text.splitlines()[-1] if r.text else ''}")
        return r.good

    def install(self):
        if not self.pm:
            die("no supported package manager found (apt/dnf/yum/pacman/zypper). "
                "Install Apache, PHP and MySQL manually, then re-run with "
                "--skip-install.")
        step(f"Installing packages with {self.pm} ({self.distro})")
        run(self.profile["refresh"], timeout=1800, quiet=True)
        self._install(self.profile["apache"], "apache")
        self._install(self.profile["php"], "php")
        self._install(self.profile.get("extra", []), "tools")
        if not which("mysql", "mariadb"):
            for group in self.profile["mysql"]:
                if self._install(group, "database server") and which("mysql", "mariadb"):
                    break
        self.detect()
        if self.pm == "apt":
            run(["a2enmod", "rewrite", "headers", "expires", "setenvif"], quiet=True)
            if self.php.fpm_service and not self.php.apache_module:
                run(["a2enmod", "proxy", "proxy_fcgi"], quiet=True)
                run(["a2enconf", f"{self.php.version[:3]}-fpm"], quiet=True)
        if self.pm == "zypper":
            run(["a2enmod", "rewrite", "php8", "headers"], quiet=True)
        if self.pm == "pacman":
            self._init_mariadb_datadir()
        if not self.apache.binary or not self.php.binary or not self.mysql.client:
            die("apache/php/mysql still missing after install; "
                "check the package manager output with --verbose")

    def _init_mariadb_datadir(self):
        if Path("/var/lib/mysql/mysql").is_dir():
            return
        info("initialising the MariaDB data directory")
        run(["mariadb-install-db", "--user=mysql", "--basedir=/usr",
             "--datadir=/var/lib/mysql"], timeout=600)

    # -- config -------------------------------------------------------------
    def php_apache_block(self) -> str:
        p = self.php
        if p.apache_module and self.pm in ("pacman",):
            return "\n".join([
                f'LoadModule php_module "{posix(p.apache_module)}"',
                'Include conf/extra/php_module.conf',
            ])
        # debian/suse/rhel wire php up through their own conf snippets
        return ""

    def apache_prepare_main(self, text: str) -> str:
        if self.pm == "pacman":
            text = prefer_prefork(text)
            for mod in APACHE_MODULES:
                text = uncomment_module(text, mod)
        return text

    def apache_apply(self, block: str):
        # keep the distro layout: sites-available (debian) / conf.d / vhosts.d
        if self.pm == "pacman":
            target = Path("/etc/httpd/conf/extra/wasql.conf")
            write_text(target, f"{SENTINEL_BEGIN}\n{block}\n{SENTINEL_END}\n")
            conf = self.apache.conf
            if conf:
                backup(conf)
                text = self.apache_prepare_main(read_text(conf))
                text = set_listen(text, self.s.port)
                text = replace_block(text, f'Include conf/extra/wasql.conf')
                write_text(conf, text)
            ok(f"wrote {target}")
            return
        if self.apache.ports_conf and self.s.port != 80:
            backup(self.apache.ports_conf)
            write_text(self.apache.ports_conf,
                       set_listen(read_text(self.apache.ports_conf), self.s.port))
        super().apache_apply(block)

    def selinux_fixup(self):
        r = run(["getenforce"], quiet=True, allow_dry=False)
        if not r.good or "Enforcing" not in r.out:
            return
        step("Adjusting SELinux for the WaSQL paths")
        run(["setsebool", "-P", "httpd_can_network_connect_db", "1"], quiet=True)
        run(["setsebool", "-P", "httpd_can_network_connect", "1"], quiet=True)
        run(["setsebool", "-P", "httpd_execmem", "1"], quiet=True)
        paths_ro = [self.s.wasql, self.s.docroot]
        paths_rw = [self.s.wasql / "php" / "temp", self.s.wasql / "logs",
                    self.s.wasql / "php" / "schema", self.s.docroot / "w_min",
                    self.s.docroot / "images"]
        if which("semanage"):
            for p in paths_ro:
                run(["semanage", "fcontext", "-a", "-t", "httpd_sys_content_t",
                     f"{p}(/.*)?"], quiet=True)
            for p in paths_rw:
                run(["semanage", "fcontext", "-a", "-t", "httpd_sys_rw_content_t",
                     f"{p}(/.*)?"], quiet=True)
            for p in paths_ro:
                run(["restorecon", "-R", str(p)], quiet=True)
            ok("SELinux file contexts applied")
        else:
            for p in paths_ro:
                run(["chcon", "-R", "-t", "httpd_sys_content_t", str(p)], quiet=True)
            for p in paths_rw:
                run(["chcon", "-R", "-t", "httpd_sys_rw_content_t", str(p)], quiet=True)
            warn("semanage not available; used chcon (labels reset on relabel)")

    # -- services -----------------------------------------------------------
    def apache_restart(self) -> Result:
        svc = self.apache.service
        if self.php.fpm_service:
            run(["systemctl", "enable", "--now", self.php.fpm_service], quiet=True)
        run(["systemctl", "enable", svc], quiet=True)
        r = run(["systemctl", "restart", svc])
        if not r.good:
            r2 = run(["systemctl", "status", svc, "--no-pager", "-l"], quiet=True)
            r.err = (r.err + "\n" + r2.out).strip()
        return r

    def mysql_start(self) -> Result:
        svc = self.mysql.service or self._mysql_service()
        if not svc:
            return Result(1, "", "no mysql/mariadb service found")
        self.mysql.service = svc
        run(["systemctl", "enable", svc], quiet=True)
        r = run(["systemctl", "restart", svc])
        for _ in range(30):
            if port_in_use(3306) or Path("/var/run/mysqld/mysqld.sock").exists():
                return Result(0, f"{svc} running", "")
            time.sleep(1)
        return r


