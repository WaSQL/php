class MySQLAdmin:
    """Talks to the local server through the mysql client, trying the login
    strategies a fresh install could plausibly be in."""

    def __init__(self, client: Path, root_pass: str, allow_sudo: bool):
        self.client = client
        self.root_pass = root_pass
        self.allow_sudo = allow_sudo and not IS_WIN
        self.strategy: Optional[dict] = None

    def _candidates(self) -> list[dict]:
        c = []
        if self.root_pass:
            c.append(dict(user="root", password=self.root_pass, sudo=False))
            if self.allow_sudo:
                c.append(dict(user="root", password=self.root_pass, sudo=True))
        c.append(dict(user="root", password="", sudo=False))
        if self.allow_sudo:
            c.append(dict(user="root", password="", sudo=True))
            c.append(dict(user="root", password="", sudo=True, socket=True))
        return c

    def _cmd(self, strat: dict, sql: str, database: Optional[str]) -> tuple[list[str], Optional[Path]]:
        args: list[str] = []
        tmp: Optional[Path] = None
        if strat.get("password"):
            fd, name = tempfile.mkstemp(prefix="wasql-my-", suffix=".cnf")
            os.close(fd)
            tmp = Path(name)
            pw = strat["password"].replace("\\", "\\\\").replace('"', '\\"')
            write_text(tmp, f'[client]\nuser={strat["user"]}\npassword="{pw}"\n', 0o600)
            args += [f"--defaults-file={tmp}"]
        else:
            args += ["--user=" + strat["user"]]
        args += ["--batch", "--raw", "--connect-timeout=10"]
        if database:
            args += [database]
        args += ["-e", sql]
        cmd = [str(self.client)] + args
        if strat.get("sudo") and os.geteuid() != 0:
            cmd = ["sudo", "-n"] + cmd
        elif strat.get("sudo"):
            pass  # already root
        return cmd, tmp

    def sql(self, statements: str, database: Optional[str] = None,
            quiet: bool = True) -> Result:
        if DRY_RUN and not re.match(r"\s*(SELECT|SHOW)\b", statements, re.I):
            info(f"{C.DIM}[dry-run] mysql: {statements[:120]}{C.OFF}")
            return Result(0, "", "")
        strats = [self.strategy] if self.strategy else self._candidates()
        last = Result(1, "", "no mysql login strategy worked")
        for strat in strats:
            if strat is None:
                continue
            cmd, tmp = self._cmd(strat, statements, database)
            r = run(cmd, quiet=quiet, timeout=600, allow_dry=False)
            if tmp:
                tmp.unlink(missing_ok=True)
            if r.good:
                self.strategy = strat
                return r
            last = r
            if "Access denied" not in r.text and "denied" not in r.text.lower():
                # a real SQL error, not an auth problem - stop guessing
                if self.strategy or "ERROR 1" in r.text:
                    return r
        return last

    def connect_ok(self) -> bool:
        return self.sql("SELECT 1;").good

    def describe_login(self) -> str:
        if not self.strategy:
            return "unknown"
        bits = ["root"]
        if self.strategy.get("password"):
            bits.append("password")
        else:
            bits.append("no password")
        if self.strategy.get("sudo"):
            bits.append("via sudo socket")
        return ", ".join(bits)


def sql_quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace("'", "\\'")


def setup_database(s: Settings, admin: MySQLAdmin) -> bool:
    db, user, pw = s.db_name, s.db_user, sql_quote(s.db_pass)
    if not admin.connect_ok():
        warn("could not log into MySQL as root automatically.\n"
             "         Create the database manually:\n"
             f"           CREATE DATABASE `{db}` CHARACTER SET utf8mb4;\n"
             f"           CREATE USER '{user}'@'%' IDENTIFIED BY '{s.db_pass}';\n"
             f"           GRANT ALL PRIVILEGES ON *.* TO '{user}'@'%' WITH GRANT OPTION;")
        return False
    info(f"connected to MySQL ({admin.describe_login()})")

    if s.mysql_root_pass and not (admin.strategy or {}).get("password"):
        r = admin.sql("ALTER USER 'root'@'localhost' IDENTIFIED BY '"
                      + sql_quote(s.mysql_root_pass) + "'; FLUSH PRIVILEGES;")
        if r.good:
            ok("set the MySQL root password")
            admin.strategy = dict(user="root", password=s.mysql_root_pass, sudo=False)
            admin.root_pass = s.mysql_root_pass
        else:
            warn(f"could not set the root password: {r.text.splitlines()[:1]}")

    r = admin.sql(f"CREATE DATABASE IF NOT EXISTS `{db}` "
                  "CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;")
    if not r.good:
        warn(f"create database failed: {r.text}")
        return False
    ok(f"database `{db}` ready")

    grants = "; ".join(
        [f"CREATE USER IF NOT EXISTS '{user}'@'{h}' IDENTIFIED BY '{pw}'"
         for h in ("localhost", "%")] +
        [f"ALTER USER '{user}'@'{h}' IDENTIFIED BY '{pw}'"
         for h in ("localhost", "%")] +
        [f"GRANT ALL PRIVILEGES ON *.* TO '{user}'@'{h}' WITH GRANT OPTION"
         for h in ("localhost", "%")] +
        ["FLUSH PRIVILEGES"]) + ";"
    r = admin.sql(grants)
    if not r.good and re.search(r"policy|password", r.text, re.I):
        info("password policy rejected the password; relaxing it for this box")
        admin.sql("SET GLOBAL validate_password.policy=LOW;", quiet=True)
        admin.sql("SET GLOBAL validate_password.length=4;", quiet=True)
        admin.sql("SET GLOBAL validate_password_policy=LOW;", quiet=True)
        admin.sql("SET GLOBAL validate_password_length=4;", quiet=True)
        r = admin.sql(grants)
    if not r.good:
        warn(f"could not create/grant the WaSQL user: {r.text}")
        return False
    ok(f"user '{user}' created with full privileges")
    return True


def tune_mysql(s: Settings, admin: MySQLAdmin, stack: Stack) -> None:
    """Relax sql_mode (WaSQL predates STRICT/ONLY_FULL_GROUP_BY) and raise
    max_allowed_packet so backups/restores work."""
    if not s.relax_sql_mode:
        return
    persisted = admin.sql(
        "SET PERSIST sql_mode='NO_ENGINE_SUBSTITUTION'; "
        "SET PERSIST max_allowed_packet=268435456;").good
    if persisted:
        ok("sql_mode and max_allowed_packet persisted (SET PERSIST)")
        return
    block = ("[mysqld]\n"
             "sql_mode=NO_ENGINE_SUBSTITUTION\n"
             "max_allowed_packet=256M\n"
             "innodb_strict_mode=0\n")
    target = None
    if stack.mysql.conf_dir and stack.mysql.conf_dir.is_dir():
        target = stack.mysql.conf_dir / "99-wasql.cnf"
        write_text(target, f"# {SENTINEL_BEGIN}\n{block}# {SENTINEL_END}\n")
    elif stack.mysql.conf_file and stack.mysql.conf_file.is_file():
        target = stack.mysql.conf_file
        backup(target)
        write_text(target, replace_block(read_text(target), block))
    if target:
        ok(f"wrote MySQL tuning to {target}")
        r = stack.mysql_start()
        if not r.good:
            warn("MySQL did not restart cleanly after tuning; check the service")
    else:
        warn("could not find a MySQL config dir; sql_mode left at the default "
             "(WaSQL may complain about strict mode)")


