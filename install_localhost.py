class MacStack(Stack):
    label = "macos"

    def __init__(self, s: Settings):
        super().__init__(s)
        self.user = invoking_user()
        self.brew = first_existing("/opt/homebrew/bin/brew",
                                   "/usr/local/bin/brew") or which("brew")
        self.prefix = Path("/opt/homebrew") if self.brew and \
            str(self.brew).startswith("/opt/homebrew") else Path("/usr/local")

    # brew refuses to run as root, so bounce back to the invoking user
    def _brew(self, *args: str, timeout: int = 2400) -> Result:
        if not self.brew:
            return Result(127, "", "brew not found")
        if os.geteuid() == 0 and self.user:
            return run(["sudo", "-u", self.user, "-H", str(self.brew), *args],
                       timeout=timeout)
        return run([str(self.brew), *args], timeout=timeout)

    def detect(self):
        if self.brew:
            r = run([str(self.brew), "--prefix"], quiet=True, allow_dry=False)
            if r.good and r.out:
                self.prefix = Path(r.out.strip())
        pfx = self.prefix
        a = self.apache
        a.binary = first_existing(pfx / "opt/httpd/bin/httpd", pfx / "bin/httpd")
        a.ctl = first_existing(pfx / "bin/apachectl", pfx / "opt/httpd/bin/apachectl")
        a.root = first_existing(pfx / "opt/httpd")
        a.conf = first_existing(pfx / "etc/httpd/httpd.conf")
        a.modules_dir = first_existing(pfx / "opt/httpd/lib/httpd/modules")
        a.user, a.group = "_www", "_www"
        a.service = "httpd"
        p = self.php
        p.binary = first_existing(pfx / "opt/php/bin/php", pfx / "bin/php") or which("php")
        p.apache_module = first_existing(pfx / "opt/php/lib/httpd/modules/libphp.so",
                                        pfx / "lib/httpd/modules/libphp.so")
        if p.binary:
            v = run([str(p.binary), "-r", "echo PHP_VERSION;"], quiet=True,
                    allow_dry=False)
            p.version = v.out.strip()
            r = run([str(p.binary), "-i"], quiet=True, allow_dry=False)
            m = re.search(r"Loaded Configuration File => (\S+)", r.out)
            if m and m.group(1) != "(none)":
                p.ini = Path(m.group(1))
            m = re.search(r"Scan this dir for additional .ini files => (\S+)", r.out)
            if m and m.group(1) != "(none)":
                p.ini_dirs = [Path(m.group(1))]
        m = self.mysql
        m.client = first_existing(pfx / "opt/mysql/bin/mysql", pfx / "bin/mysql") or which("mysql")
        m.server_bin = first_existing(pfx / "opt/mysql/bin/mysqld")
        m.conf_file = first_existing(pfx / "etc/my.cnf")
        m.conf_dir = first_existing(pfx / "etc/my.cnf.d")
        m.service = "mysql"

    def install(self):
        if not self.brew:
            step("Installing Homebrew")
            if not self.user:
                die("Homebrew cannot be installed as root. Run this script as a "
                    "normal user (it will sudo where needed).")
            r = run(["sudo", "-u", self.user, "-H", "bash", "-c",
                     f'NONINTERACTIVE=1 /bin/bash -c "$(curl -fsSL {BREW_INSTALL_URL})"'],
                    timeout=3600)
            if not r.good:
                die("Homebrew install failed:\n" + r.text)
            self.brew = first_existing("/opt/homebrew/bin/brew", "/usr/local/bin/brew")
            self.detect()
        want = []
        if not self.apache.binary:
            want.append("httpd")
        if not self.php.apache_module:
            want.append("php")
        if not self.mysql.client:
            want.append("mysql")
        if not want:
            ok("httpd, php and mysql are already installed via Homebrew")
            return
        step(f"Installing via Homebrew: {', '.join(want)}")
        self._brew("update", timeout=1200)
        for pkg in want:
            r = self._brew("install", pkg)
            if not r.good and "already installed" not in r.text.lower():
                warn(f"brew install {pkg} failed:\n{r.text[:400]}")
        self.detect()

    def php_apache_block(self) -> str:
        p = self.php
        if not p.apache_module:
            warn("brew php libphp.so not found - PHP will not run under Apache")
            return ""
        return "\n".join([
            f'LoadModule php_module "{posix(p.apache_module)}"',
            '<FilesMatch "\\.(php|phtml)$">',
            "    SetHandler application/x-httpd-php",
            "</FilesMatch>",
        ])

    def apache_prepare_main(self, text: str) -> str:
        text = super().apache_prepare_main(text)
        return prefer_prefork(text)

    def apache_restart(self) -> Result:
        # `sudo brew services` is the documented way to run httpd on port 80,
        # so this one stays as root instead of dropping to the invoking user
        r = run([str(self.brew), "services", "restart", "httpd"], quiet=True) \
            if self.brew else Result(1, "", "brew not found")
        if not r.good and self.apache.ctl:
            run([str(self.apache.ctl), "-k", "stop"], quiet=True)
            time.sleep(1)
            r = run([str(self.apache.ctl), "-k", "start"])
        return r

    def mysql_start(self) -> Result:
        r = self._brew("services", "start", "mysql")
        if not r.good:
            warn("brew services start mysql failed; trying mysql.server")
            srv = first_existing(self.prefix / "opt/mysql/bin/mysqld_safe")
            if srv:
                run(["bash", "-c", f"{srv} --user=mysql &"], quiet=True)
                time.sleep(5)
        for _ in range(20):
            if port_in_use(3306):
                return Result(0, "mysql up", "")
            time.sleep(1)
        return r


