class C:
    """ANSI colors (disabled when output is not a tty)."""
    BOLD = "\033[1m"
    DIM = "\033[2m"
    RED = "\033[31m"
    GREEN = "\033[32m"
    YELLOW = "\033[33m"
    BLUE = "\033[36m"
    OFF = "\033[0m"

    @classmethod
    def disable(cls):
        for k in ("BOLD", "DIM", "RED", "GREEN", "YELLOW", "BLUE", "OFF"):
            setattr(cls, k, "")


def _init_console():
    if not sys.stdout.isatty() or os.environ.get("NO_COLOR"):
        C.disable()
        return
    if IS_WIN:  # enable VT sequences on legacy consoles
        try:
            k = ctypes.windll.kernel32
            k.SetConsoleMode(k.GetStdHandle(-11), 7)
        except Exception:
            C.disable()


_step_no = 0


def step(msg: str):
    global _step_no
    _step_no += 1
    print(f"\n{C.BOLD}{C.BLUE}[{_step_no}] {msg}{C.OFF}")


