class WindowsStack(Stack):
    label = "windows"
    APACHE_SERVICE = "Apache2.4"
    MYSQL_SERVICE = "MySQL"

    def detect(self):
        a = self.apache
        a.binary = first_existing(
            r"C:\tools\Apache24\bin\httpd.exe",
            r"C:\Apache24\bin\httpd.exe",
            r"C:\Program Files\Apache24\bin\httpd.exe",
            r"C:\Apache2*\bin\httpd.exe",
            r"C:\xampp\apache\bin\httpd.exe",
            r"C:\wamp*\bin\apache\apache*\bin\httpd.exe",
        ) or which("httpd")
        if a.binary:
            a.root = a.binary.parent.parent
            a.conf = first_existing(a.root / "conf" / "httpd.conf")
            a.modules_dir = a.root / "modules"
            a.service = self.APACHE_SERVICE
            a.user, a.group = "", ""
        p = self.php
        p.binary = first_existing(
            r"C:\tools\php*\php.exe", r"C:\php*\php.exe",
            r"C:\Program Files\php*\php.exe", r"C:\xampp\php\php.exe",
        ) or which("php")
        if p.binary:
            self._fill_php(p.binary.parent)
        m = self.mysql
        m.client = first_existing(
            r"C:\tools\mysql\current\bin\mysql.exe",
            r"C:\Program Files\MySQL\MySQL Server *\bin\mysql.exe",
            r"C:\tools\mysql*\bin\mysql.exe",
            r"C:\xampp\mysql\bin\mysql.exe",
        ) or which("mysql")
        if m.client:
            m.server_bin = first_existing(m.client.parent / "mysqld.exe")
            m.service = self._find_mysql_service() or self.MYSQL_SERVICE
            m.conf_file = first_existing(
                m.client.parent.parent / "my.ini",
                r"C:\ProgramData\MySQL\MySQL Server *\my.ini",
                r"C:\tools\mysql\current\my.ini",
            )

    def _fill_php(self, home: Path):
        p = self.php
        p.home = home
        p.binary = home / "php.exe"
        p.ini = home / "php.ini"
        p.apache_module = first_existing(home / "php*apache2_4.dll")
        v = run([str(p.binary), "-r", "echo PHP_VERSION;"], quiet=True,
                allow_dry=False)
        p.version = v.out.strip() if v.good else ""

    def _find_mysql_service(self) -> Optional[str]:
        r = powershell("Get-Service | Where-Object {$_.Name -match "
                       "'mysql|mariadb'} | Select-Object -First 1 "
                       "-ExpandProperty Name", allow_dry=False)
        return r.out.strip() or None

    # -- install ------------------------------------------------------------
    def install(self):
        need_apache = self.apache.binary is None
        need_php = self.php.apache_module is None
        need_mysql = self.mysql.client is None
        if not (need_apache or need_php or need_mysql):
            ok("Apache, PHP (thread-safe) and MySQL are all present")
            return
        if need_apache or need_mysql:
            self._ensure_choco()
        if need_apache:
            step("Installing Apache (Chocolatey: apache-httpd)")
            self._choco("apache-httpd")
            self._choco("vcredist140")
        if need_mysql:
            step("Installing MySQL (Chocolatey: mysql)")
            self._choco("mysql")
        if need_php:
            step("Installing PHP (thread-safe build from windows.php.net)")
            self._install_php_windows()
        self.detect()
        missing = [n for n, v in (("apache", self.apache.binary),
                                  ("php", self.php.binary),
                                  ("mysql", self.mysql.client)) if not v]
        if missing:
            die("could not find these after installation: " + ", ".join(missing) +
                "\n  Install them manually, then re-run with --skip-install.")

    def _ensure_choco(self):
        if which("choco"):
            return
        step("Installing Chocolatey (Windows package manager)")
        r = powershell(CHOCO_INSTALL_PS, timeout=900)
        if not r.good:
            die("Chocolatey install failed:\n" + r.text +
                "\n  Install Apache/MySQL manually (or install Chocolatey "
                "yourself) and re-run with --skip-install.")
        choco = first_existing(r"C:\ProgramData\chocolatey\bin\choco.exe")
        if choco:
            os.environ["PATH"] = f"{choco.parent};{os.environ.get('PATH','')}"
        ok("Chocolatey installed")

    def _choco(self, pkg: str, params: str = ""):
        choco = which("choco") or first_existing(
            r"C:\ProgramData\chocolatey\bin\choco.exe")
        if not choco:
            die("choco.exe not found")
        cmd = [str(choco), "install", pkg, "-y", "--no-progress",
               "--ignore-checksums"]
        if params:
            cmd += ["--params", params]
        r = run(cmd, timeout=2400)
        if not r.good and "already installed" not in r.text.lower():
            warn(f"choco install {pkg} returned {r.code}; continuing "
                 f"(see output with --verbose)")

    def _install_php_windows(self):
        """Fetch the newest x64 thread-safe PHP zip (mod_php needs TS)."""
        code, html = http_get(WIN_PHP_RELEASES_URL, timeout=60)
        if code != 200:
            die(f"could not read {WIN_PHP_RELEASES_URL} ({code}). "
                "Install PHP (thread safe, x64) manually and re-run with "
                "--skip-install.")
        cands = []
        for m in re.finditer(r'php-(\d+)\.(\d+)\.(\d+)-Win32-vs(\d+)-x64\.zip',
                             html):
            name = m.group(0)
            if "-nts-" in name or "debug" in name.lower():
                continue
            major, minor, patch, vs = (int(m.group(i)) for i in range(1, 5))
            if self.s.php_version and f"{major}.{minor}" != self.s.php_version:
                continue
            cands.append(((major, minor, patch, vs), name))
        if not cands:
            die("no thread-safe PHP build found on windows.php.net"
                + (f" for branch {self.s.php_version}" if self.s.php_version else ""))
        ver, name = sorted(cands, reverse=True)[0]
        target = Path(f"C:/php-{ver[0]}.{ver[1]}")
        tmp = Path(tempfile.gettempdir()) / name
        download(WIN_PHP_RELEASES_URL + name, tmp, label=name)
        info(f"extracting to {target}")
        if not DRY_RUN:
            target.mkdir(parents=True, exist_ok=True)
            with zipfile.ZipFile(tmp) as z:
                z.extractall(target)
            tmp.unlink(missing_ok=True)
        self._fill_php(target)
        self._add_to_machine_path(target)
        ok(f"PHP {ver[0]}.{ver[1]}.{ver[2]} (TS, vs{ver[3]}) installed at {target}")

    def _add_to_machine_path(self, *dirs: Path):
        parts = [posix(d).replace("/", "\\") for d in dirs if d]
        if not parts:
            return
        script = (
            "$p=[Environment]::GetEnvironmentVariable('Path','Machine');"
            "$add=@(" + ",".join(f"'{d}'" for d in parts) + ");"
            "$cur=$p -split ';';"
            "foreach($a in $add){if($cur -notcontains $a){$p=$p.TrimEnd(';')+';'+$a}};"
            "[Environment]::SetEnvironmentVariable('Path',$p,'Machine');"
        )
        powershell(script)
        for d in parts:
            os.environ["PATH"] = f"{d};{os.environ.get('PATH','')}"

    # -- php config ---------------------------------------------------------
    def php_write_ini(self):
        p = self.php
        if not p.home:
            warn("PHP home unknown; skipping php.ini configuration")
            return
        ini = p.home / "php.ini"
        if not ini.is_file():
            src = first_existing(p.home / "php.ini-development",
                                 p.home / "php.ini-production")
            if src and not DRY_RUN:
                shutil.copy2(src, ini)
                info(f"created php.ini from {src.name}")
        p.ini = ini
        backup(ini)
        text = read_text(ini)
        ext_dir = p.home / "ext"
        text = set_ini_value(text, "extension_dir", f'"{posix(ext_dir)}"')
        enabled = []
        for ext in WIN_EXTENSIONS:
            if (ext_dir / f"php_{ext}.dll").is_file() or DRY_RUN:
                text = enable_win_extension(text, ext)
                enabled.append(ext)
        settings = dict(PHP_INI_SETTINGS)
        settings["date.timezone"] = self.s.timezone
        settings["error_log"] = f'"{posix(self.s.wasql / "logs" / "php_errors.log")}"'
        for k, v in settings.items():
            text = set_ini_value(text, k, v)
        write_text(ini, text)
        ok(f"configured {ini}")
        debug("extensions enabled: " + ", ".join(enabled))

    # -- apache config ------------------------------------------------------
    def apache_prepare_main(self, text: str) -> str:
        text = super().apache_prepare_main(text)
        if self.apache.root:
            text = re.sub(r'^\s*Define\s+SRVROOT\s+".*?"\s*$',
                          f'Define SRVROOT "{posix(self.apache.root)}"',
                          text, count=1, flags=re.M)
        return text

    def php_apache_block(self) -> str:
        p = self.php
        lines = []
        if p.apache_module:
            # LoadFile the shared libs PHP needs; the service does not pick up
            # a freshly changed machine PATH until a reboot.
            for pat in ("libssh2.dll", "libcrypto-*-x64.dll", "libssl-*-x64.dll",
                        "libsodium.dll", "nghttp2.dll", "libzip.dll",
                        "libpq.dll", "libcurl.dll"):
                for hit in sorted(glob.glob(str(p.home / pat))):
                    lines.append(f'LoadFile "{posix(hit)}"')
            mod = "php_module" if "php8" in p.apache_module.name or \
                  "php9" in p.apache_module.name else "php7_module"
            lines.append(f'LoadModule {mod} "{posix(p.apache_module)}"')
            lines.append(f'PHPIniDir "{posix(p.home)}"')
            lines.append('<FilesMatch "\\.(php|phtml)$">')
            lines.append("    SetHandler application/x-httpd-php")
            lines.append("</FilesMatch>")
        else:
            warn("no php*apache2_4.dll found - PHP will not run under Apache")
        return "\n".join(lines)

    # -- services -----------------------------------------------------------
    def apache_restart(self) -> Result:
        svc = self.apache.service or self.APACHE_SERVICE
        exists = powershell(f"if(Get-Service -Name '{svc}' "
                            "-ErrorAction SilentlyContinue){'yes'}")
        if "yes" not in exists.out:
            info(f"registering the {svc} service")
            run([str(self.apache.binary), "-k", "install", "-n", svc])
        r = run([str(self.apache.binary), "-k", "restart", "-n", svc])
        if not r.good:
            run(["sc", "start", svc], quiet=True)
            r = run([str(self.apache.binary), "-k", "start", "-n", svc])
        powershell(f"Set-Service -Name '{svc}' -StartupType Automatic")
        return r

    def mysql_start(self) -> Result:
        svc = self.mysql.service or self.MYSQL_SERVICE
        r = powershell(f"$s=Get-Service -Name '{svc}' -ErrorAction "
                       "SilentlyContinue; if($s){ if($s.Status -ne 'Running')"
                       "{Start-Service $s}; Set-Service $s.Name -StartupType "
                       "Automatic; 'running' } else { 'missing' }")
        if "missing" in r.out and self.mysql.server_bin:
            info("MySQL service not registered; installing it")
            run([str(self.mysql.server_bin), "--install", svc])
            r = powershell(f"Start-Service '{svc}'; 'running'")
        return r


