def wasql_config_xml(s: Settings) -> None:
    """Create config.xml if absent; otherwise leave the developer's alone."""
    cfg = s.wasql / "config.xml"
    existing = read_existing_config(cfg)
    if cfg.is_file() and existing.get("_has_localhost") and not s.force_config:
        ok(f"config.xml already maps localhost -> `{existing.get('dbname')}` "
           "(left untouched)")
        return
    port_hosts = ""
    if s.port != 80:
        port_hosts = (f'\t<host name="localhost:{s.port}" sameas="localhost" />\n'
                      f'\t<host name="127.0.0.1:{s.port}" sameas="localhost" />\n')
    body = f"""<hosts>
\t<!--
\t\tGenerated by install_localhost.py for local development.
\t\tsample.config.xml documents every available attribute.
\t-->
\t<database
\t\tname="wasql_local"
\t\tdisplayname="WaSQL Local"
\t\tdbtype="mysqli"
\t\tdbhost="{s.db_host}"
\t\tdbname="{s.db_name}"
\t\tdbuser="{s.db_user}"
\t\tdbpass="{s.db_pass}"
\t/>
\t<allhost
\t\tpaging="50"
\t\tmarkdown="1"
\t\tdatabase_sessions="1"
\t\taccess="all"
\t\tmissing_page="passthru"
\t/>
\t<host name="localhost" database="wasql_local" cron="1" insecure="1" />
\t<host name="127.0.0.1" sameas="localhost" />
{port_hosts}</hosts>
"""
    if cfg.is_file():
        backup(cfg)
        if not existing.get("_has_localhost"):
            # keep the developer's file, just add a localhost host + database
            text = read_text(cfg)
            add = (f'\t<database name="wasql_local" displayname="WaSQL Local" '
                   f'dbtype="mysqli" dbhost="{s.db_host}" dbname="{s.db_name}" '
                   f'dbuser="{s.db_user}" dbpass="{s.db_pass}" />\n'
                   f'\t<host name="localhost" database="wasql_local" cron="1" />\n'
                   f'\t<host name="127.0.0.1" sameas="localhost" />\n')
            if "</hosts>" in text:
                text = text.replace("</hosts>", add + "</hosts>", 1)
                write_text(cfg, text)
                ok("added a localhost host entry to the existing config.xml")
                return
        write_text(cfg, body)
        ok(f"rewrote {cfg} (previous copy saved as config.xml.wasql-bak)")
        return
    write_text(cfg, body)
    ok(f"created {cfg}")


def wasql_filesystem(s: Settings, stack: Stack) -> None:
    """Directories, permissions and .htaccess WaSQL expects to exist."""
    web_user = stack.apache.user if not IS_WIN else None
    ensure_dir(s.wasql / "php" / "temp", writable=True, owner=web_user)
    ensure_dir(s.wasql / "logs", writable=True, owner=web_user)
    # the setup wizard unzips a site template inside php/schema, then removes it
    if not IS_WIN and (s.wasql / "php" / "schema").is_dir() and not DRY_RUN:
        try:
            os.chmod(s.wasql / "php" / "schema", 0o777)
        except OSError as e:
            debug(f"chmod php/schema: {e}")
    ensure_dir(s.docroot, writable=False)
    ensure_dir(s.docroot / "images", writable=True, owner=web_user)
    ensure_dir(s.docroot / "w_min", writable=True, owner=web_user)
    ensure_traversable(s.wasql)
    if s.docroot != s.wasql:
        ensure_traversable(s.docroot)

    ht = s.docroot / ".htaccess"
    sample = s.wasql / "sample.htaccess"
    if not ht.is_file() and sample.is_file() and not DRY_RUN:
        shutil.copy2(sample, ht)
        ok(f"created {ht} from sample.htaccess")
    if s.docroot != s.wasql:
        # aliases cover /php and /wfiles, but a symlink keeps relative paths sane
        for name in ("php", "wfiles"):
            link = s.docroot / name
            target = s.wasql / name
            if not link.exists() and target.is_dir() and not IS_WIN and not DRY_RUN:
                try:
                    link.symlink_to(target)
                    debug(f"symlinked {link} -> {target}")
                except OSError as e:
                    debug(f"symlink {link}: {e}")
    ok("WaSQL directories and permissions prepared")


def apache_vhost(s: Settings, stack: Stack) -> str:
    w, d = posix(s.wasql), posix(s.docroot)
    php_block = getattr(stack, "php_apache_block", lambda: "")()
    dir_opts = "Options Indexes FollowSymLinks ExecCGI"
    # when the docroot IS the wasql dir one Directory block covers both
    wasql_dir_block = "" if d == w else f"""
    <Directory "{w}">
        {dir_opts}
        AllowOverride All
        Require local
    </Directory>
"""
    body = f"""# WaSQL local development - {s.wasql}
{php_block}

<VirtualHost *:{s.port}>
    ServerName localhost
    ServerAlias 127.0.0.1
    DocumentRoot "{d}"
    DirectoryIndex index.php index.html index.htm

    Alias /php/ "{w}/php/"
    Alias /wfiles/ "{w}/wfiles/"
{wasql_dir_block}
    <Directory "{d}">
        {dir_opts}
        AllowOverride All
        Require local

        RewriteEngine On
        RewriteBase /
        # let real files and directories through
        RewriteCond %{{REQUEST_FILENAME}} !-f
        RewriteCond %{{REQUEST_FILENAME}} !-d
        RewriteCond %{{REQUEST_URI}} !=/server-status
        # everything else is a WaSQL page
        RewriteRule ^(.*)$ /php/index.php?_view=$1 [L,QSA]
        RewriteRule ^$ /php/index.php?_view=index [L,QSA]
    </Directory>
</VirtualHost>
"""
    return body


def configure_apache(s: Settings, stack: Stack) -> bool:
    step("Configuring Apache")
    if not stack.apache.conf and not stack.apache.conf_dir:
        warn("no Apache configuration directory found; skipping")
        return False
    if stack.apache.conf and stack.apache.include_via_conf is False and \
            stack.apache.conf.is_file() and not stack.apache.debian_site:
        # distro layout: still make sure the modules we need are on
        backup(stack.apache.conf)
        text = stack.apache_prepare_main(read_text(stack.apache.conf))
        if s.port != 80 and not stack.apache.ports_conf:
            text = set_listen(text, s.port)
        write_text(stack.apache.conf, text)
    stack.apache_apply(apache_vhost(s, stack))
    t = stack.apache_configtest()
    if not t.good and "Syntax OK" not in t.text:
        warn("apache configtest reported a problem:\n" +
             "\n".join(t.text.splitlines()[-12:]))
        return False
    ok("apache configuration syntax is valid")
    return True


