class Stack:
    """Platform behaviour: locate/install the stack and start its services."""

    label = "generic"

    def __init__(self, s: Settings):
        self.s = s
        self.apache = Apache()
        self.php = Php()
        self.mysql = MySQLPaths()

    # -- discovery / install ------------------------------------------------
    def detect(self):
        raise NotImplementedError

    def install(self):
        raise NotImplementedError

    # -- services -----------------------------------------------------------
    def apache_restart(self) -> Result:
        raise NotImplementedError

    def mysql_start(self) -> Result:
        raise NotImplementedError

    def apache_configtest(self) -> Result:
        if self.apache.ctl:
            return run([str(self.apache.ctl), "configtest"])
        if self.apache.binary:
            return run([str(self.apache.binary), "-t"])
        return Result(1, "", "no apache binary found")

    # -- shared config writers ---------------------------------------------
    def apache_apply(self, block: str):
        """Write the WaSQL apache config and make sure it is included."""
        if self.apache.debian_site:
            target = Path("/etc/apache2/sites-available/000-wasql.conf")
            write_text(target, f"{SENTINEL_BEGIN}\n{block}\n{SENTINEL_END}\n")
            run(["a2dissite", "000-default"], quiet=True)
            run(["a2ensite", "000-wasql"], quiet=True)
            ok(f"wrote {target} (enabled, 000-default disabled)")
            return
        if self.apache.conf_dir and not self.apache.include_via_conf:
            target = self.apache.conf_dir / "wasql.conf"
            write_text(target, f"{SENTINEL_BEGIN}\n{block}\n{SENTINEL_END}\n")
            ok(f"wrote {target}")
            return
        # generic: separate file next to httpd.conf + a single Include line
        assert self.apache.conf, "no httpd.conf located"
        target = self.apache.conf.parent / "wasql.conf"
        write_text(target, f"{SENTINEL_BEGIN}\n{block}\n{SENTINEL_END}\n")
        conf_text = read_text(self.apache.conf)
        backup(self.apache.conf)
        conf_text = self.apache_prepare_main(conf_text)
        inc = f'Include "{posix(target)}"'
        conf_text = replace_block(conf_text, f"# WaSQL local development\n{inc}")
        write_text(self.apache.conf, conf_text)
        ok(f"wrote {target} and included it from {self.apache.conf.name}")

    def apache_prepare_main(self, text: str) -> str:
        """Uncomment the modules WaSQL needs in a stock httpd.conf."""
        for mod in APACHE_MODULES:
            text = uncomment_module(text, mod)
        text = set_listen(text, self.s.port)
        return text

    def php_write_ini(self):
        """Apply PHP_INI_SETTINGS through a scan-dir drop-in when possible."""
        settings = dict(PHP_INI_SETTINGS)
        settings["date.timezone"] = self.s.timezone
        body = "\n".join(f"{k} = {v}" for k, v in settings.items())
        payload = (f"; {SENTINEL_BEGIN}\n; WaSQL local development defaults\n"
                   f"[PHP]\n{body}\n; {SENTINEL_END}\n")
        wrote = False
        for d in self.php.ini_dirs:
            if d and d.is_dir():
                write_text(d / "99-wasql.ini", payload)
                ok(f"wrote {d / '99-wasql.ini'}")
                wrote = True
        if not wrote and self.php.ini:
            backup(self.php.ini)
            text = read_text(self.php.ini)
            for k, v in settings.items():
                text = set_ini_value(text, k, v)
            write_text(self.php.ini, text)
            ok(f"updated {self.php.ini}")
        elif not wrote:
            warn("no php.ini or scan directory found; PHP limits left at defaults")


def posix(p: Path | str) -> str:
    """Apache config wants forward slashes, even on Windows."""
    return str(p).replace("\\", "/")


def uncomment_module(text: str, module: str) -> str:
    pat = re.compile(r"^(\s*)#\s*(LoadModule\s+" + re.escape(module) + r"\s+\S+)\s*$",
                     re.M)
    if pat.search(text):
        return pat.sub(r"\1\2", text)
    return text


def set_listen(text: str, port: int) -> str:
    """Point the first Listen directive at our port (adding one if absent)."""
    pat = re.compile(r"^(\s*)Listen\s+(\S+)\s*$", re.M)
    matches = list(pat.finditer(text))
    if not matches:
        return text
    first = matches[0]
    current = first.group(2)
    want = str(port)
    if current == want or current.endswith(f":{want}"):
        return text
    start, end = first.span()
    return text[:start] + f"{first.group(1)}Listen {want}" + text[end:]


def set_ini_value(text: str, key: str, value: str) -> str:
    pat = re.compile(r"^[;\s]*" + re.escape(key) + r"\s*=.*$", re.M)
    line = f"{key} = {value}"
    if pat.search(text):
        return pat.sub(line, text, count=1)
    return text.rstrip("\n") + f"\n{line}\n"


def enable_win_extension(text: str, ext: str) -> str:
    pat = re.compile(r"^\s*;\s*(extension\s*=\s*" + re.escape(ext) + r")\s*$", re.M)
    if pat.search(text):
        return pat.sub(r"\1", text)
    if re.search(r"^\s*extension\s*=\s*" + re.escape(ext) + r"\s*$", text, re.M):
        return text
    return text.rstrip("\n") + f"\nextension={ext}\n"


def prefer_prefork(text: str) -> str:
    """mod_php is not safe under the event/worker MPMs - switch to prefork."""
    for mpm in ("mpm_event_module", "mpm_worker_module"):
        text = re.sub(r"^(\s*)(LoadModule\s+" + mpm + r"\s+\S+)\s*$",
                      r"\1#\2", text, flags=re.M)
    if re.search(r"^\s*LoadModule\s+mpm_prefork_module", text, re.M):
        return uncomment_module(text, "mpm_prefork_module")
    return text


