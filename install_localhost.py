def summary(s: Settings, stack: Stack, admin: MySQLAdmin, checked: dict):
    base = f"http://localhost{'' if s.port == 80 else ':' + str(s.port)}"
    print(f"\n{C.BOLD}{'=' * 68}{C.OFF}")
    print(f"{C.BOLD}WaSQL local install summary{C.OFF}")
    print(f"{C.BOLD}{'=' * 68}{C.OFF}")
    print(f"  site            {base}/")
    print(f"  admin           {base}/php/admin.php   (login admin / admin)")
    print(f"  wasql dir       {s.wasql}")
    print(f"  document root   {s.docroot}")
    print(f"  apache          {stack.apache.binary or '?'}")
    if stack.apache.conf:
        print(f"  apache conf     {stack.apache.conf}")
    print(f"  php             {stack.php.binary or '?'}"
          f"{' (' + stack.php.version + ')' if stack.php.version else ''}")
    if stack.php.ini:
        print(f"  php.ini         {stack.php.ini}")
    print(f"  mysql client    {stack.mysql.client or '?'}")
    print(f"  database        {s.db_name}  (user {s.db_user} / {s.db_pass})")
    if s.mysql_root_pass:
        print(f"  mysql root      password set by this installer")
    print(f"  config.xml      {s.wasql / 'config.xml'}")
    print(f"  error log       {s.wasql / 'logs' / 'wasql_errors.log'}")
    if IS_LINUX:
        svc = stack.apache.service
        print(f"\n  restart apache  systemctl restart {svc}")
        print(f"  restart mysql   systemctl restart {stack.mysql.service}")
    elif IS_MAC:
        print("\n  restart apache  sudo brew services restart httpd")
        print("  restart mysql   brew services restart mysql")
    else:
        print(f"\n  restart apache  net stop {stack.apache.service} && "
              f"net start {stack.apache.service}")
        print(f"  restart mysql   net stop {stack.mysql.service} && "
              f"net start {stack.mysql.service}")
    if _WARNINGS:
        print(f"\n{C.YELLOW}{C.BOLD}{len(_WARNINGS)} warning(s):{C.OFF}")
        for w in _WARNINGS:
            print(f"  - {w.splitlines()[0]}")
    if IS_WIN:
        print(f"\n{C.DIM}  Note: the PHP directory was added to the machine "
              f"PATH; a reboot makes it visible to every process.{C.OFF}")
    healthy = bool(checked) and (checked.get("db") or {}).get("ok")
    if healthy and not _WARNINGS:
        print(f"\n{C.GREEN}{C.BOLD}Done - open {base}/ in a browser.{C.OFF}\n")
    elif healthy:
        print(f"\n{C.GREEN}Done with warnings - open {base}/ in a browser.{C.OFF}\n")
    else:
        print(f"\n{C.YELLOW}Finished, but verification did not fully pass. "
              f"Re-run with --check --verbose to dig in.{C.OFF}\n")


