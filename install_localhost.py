def ask(prompt: str, default: str, assume_yes: bool,
        choices: Optional[Iterable[str]] = None, secret: bool = False) -> str:
    if assume_yes:
        return default
    shown = f" [{default}]" if default != "" else " []"
    if choices:
        shown = f" ({'/'.join(choices)})" + shown
    while True:
        try:
            val = input(f"  {prompt}{shown}: ").strip()
        except (EOFError, KeyboardInterrupt):
            print()
            die("aborted")
        if not val:
            val = default
        if choices and val.lower() not in [c.lower() for c in choices]:
            print(f"    please answer one of: {', '.join(choices)}")
            continue
        return val


def ask_bool(prompt: str, default: bool, assume_yes: bool) -> bool:
    d = "y" if default else "n"
    return ask(prompt, d, assume_yes, choices=("y", "n")).lower().startswith("y")


def read_existing_config(cfg: Path) -> dict:
    """Pull dbname/dbuser/dbpass for host 'localhost' out of an existing
    config.xml so we configure MySQL to match what WaSQL will actually use."""
    import xml.etree.ElementTree as ET
    out: dict = {}
    if not cfg.is_file():
        return out
    try:
        root = ET.parse(str(cfg)).getroot()
    except Exception as e:
        warn(f"could not parse {cfg.name} ({e}); treating it as absent")
        return out
    dbs = {}
    for d in root.findall("database"):
        name = (d.get("name") or "").lower()
        if name:
            dbs[name] = dict(d.attrib)
    allhost = dict(root.find("allhost").attrib) if root.find("allhost") is not None else {}
    hosts = {(h.get("name") or "").lower(): dict(h.attrib) for h in root.findall("host")}
    target = hosts.get("localhost")
    if target is None:
        return out
    merged = dict(allhost)
    seen = set()
    while target is not None and "sameas" in target and target["sameas"].lower() not in seen:
        seen.add(target["sameas"].lower())
        parent = hosts.get(target["sameas"].lower())
        if parent:
            merged.update(parent)
            target = parent
        else:
            break
    merged.update(hosts.get("localhost", {}))
    dbref = (merged.get("database") or "").lower()
    if dbref in dbs:
        merged = {**dbs[dbref], **merged}
    for k in ("dbname", "dbuser", "dbpass", "dbhost", "dbtype"):
        if merged.get(k):
            out[k] = merged[k]
    out["_has_localhost"] = True
    return out


def gather_settings(args) -> Settings:
    """Ask every question up front, then never prompt again."""
    y = args.yes
    here = Path(args.wasql or Path(__file__).resolve().parent).resolve()
    if not (here / "php" / "index.php").is_file():
        die(f"{here} does not look like a WaSQL checkout "
            "(php/index.php missing). Pass --wasql <path>.")

    print(f"\n{C.BOLD}WaSQL local stack installer{C.OFF}")
    print(f"  platform : {platform.platform()}")
    print(f"  wasql    : {here}")
    existing = read_existing_config(here / "config.xml")
    if existing.get("_has_localhost"):
        print(f"  config.xml already defines host 'localhost' -> database "
              f"'{existing.get('dbname', '?')}' (it will be reused, not "
              f"overwritten)")
    print(f"\n{C.BOLD}Answer a few questions, then it runs unattended."
          f"{C.OFF}  (Enter accepts the default)\n")

    wasql = Path(ask("WaSQL directory", str(here), y)).resolve()
    docroot = Path(ask("Apache DocumentRoot", str(args.docroot or wasql), y)).resolve()
    port = int(ask("Apache port", str(args.port or DEFAULT_PORT), y))
    install_packages = (False if args.skip_install else
                        ask_bool("Install Apache/PHP/MySQL if missing?",
                                 not args.skip_install, y))
    db_name = ask("WaSQL database name",
                  args.db_name or existing.get("dbname") or DEFAULT_DB_NAME, y)
    db_user = ask("WaSQL database user",
                  args.db_user or existing.get("dbuser") or DEFAULT_DB_USER, y)
    db_pass = ask("WaSQL database password",
                  args.db_pass or existing.get("dbpass") or DEFAULT_DB_PASS, y)
    root_pass = ask("MySQL root password (blank = leave/keep as-is)",
                    args.mysql_root_pass or "", y)
    sample = ask("Install which sample site?", args.sample or DEFAULT_SAMPLE, y,
                 choices=SAMPLE_CHOICES).lower()
    relax = ask_bool("Relax MySQL sql_mode (recommended for WaSQL)?",
                     not args.strict_sql_mode, y)
    tz = ask("PHP timezone", args.timezone or PHP_INI_SETTINGS["date.timezone"], y)

    s = Settings(wasql=wasql, docroot=docroot, port=port, db_name=db_name,
                 db_user=db_user, db_pass=db_pass, mysql_root_pass=root_pass,
                 install_packages=install_packages, sample=sample,
                 relax_sql_mode=relax, force_config=args.force_config,
                 php_version=args.php_version or "", timezone=tz)

    print(f"\n{C.BOLD}Plan{C.OFF}")
    print(f"  wasql dir      : {s.wasql}")
    print(f"  document root  : {s.docroot}")
    print(f"  url            : http://localhost{'' if s.port == 80 else ':' + str(s.port)}/")
    print(f"  database       : {s.db_name} (user {s.db_user})")
    print(f"  install pkgs   : {'yes' if s.install_packages else 'no (configure only)'}")
    print(f"  sample site    : {s.sample}")
    print(f"  relax sql_mode : {'yes' if s.relax_sql_mode else 'no'}")
    if not y and not ask_bool("\nProceed?", True, False):
        die("aborted", 0)
    return s


