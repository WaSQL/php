def build_stack(s: Settings) -> Stack:
    if IS_WIN:
        return WindowsStack(s)
    if IS_MAC:
        return MacStack(s)
    if IS_LINUX:
        return LinuxStack(s)
    die(f"unsupported platform: {sys.platform}")


def parse_args(argv: list[str]):
    p = argparse.ArgumentParser(
        prog="install_localhost.py",
        description="Install and configure Apache + PHP + MySQL for WaSQL on "
                    "localhost (Windows, Linux, macOS).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="examples:\n"
               "  python3 install_localhost.py                 # ask, then run\n"
               "  python3 install_localhost.py --yes            # all defaults\n"
               "  python3 install_localhost.py --skip-install    # configure only\n"
               "  python3 install_localhost.py --check           # verify only\n")
    p.add_argument("-y", "--yes", action="store_true",
                   help="accept every default, ask nothing")
    p.add_argument("--wasql", help="path to the WaSQL checkout "
                                   "(default: this script's directory)")
    p.add_argument("--docroot", help="Apache DocumentRoot (default: the WaSQL dir)")
    p.add_argument("--port", type=int, help=f"Apache port (default {DEFAULT_PORT})")
    p.add_argument("--db-name", help=f"WaSQL database (default {DEFAULT_DB_NAME})")
    p.add_argument("--db-user", help=f"WaSQL db user (default {DEFAULT_DB_USER})")
    p.add_argument("--db-pass", help=f"WaSQL db password (default {DEFAULT_DB_PASS})")
    p.add_argument("--mysql-root-pass", help="set/use this MySQL root password")
    p.add_argument("--sample", choices=SAMPLE_CHOICES,
                   help=f"sample site to install (default {DEFAULT_SAMPLE})")
    p.add_argument("--php-version", help="Windows only: PHP branch to fetch, e.g. 8.4")
    p.add_argument("--timezone", help="PHP date.timezone")
    p.add_argument("--skip-install", action="store_true",
                   help="do not install packages, only configure what is here")
    p.add_argument("--force-config", action="store_true",
                   help="overwrite an existing config.xml (a backup is kept)")
    p.add_argument("--strict-sql-mode", action="store_true",
                   help="leave MySQL sql_mode alone (default: relax it)")
    p.add_argument("--check", action="store_true",
                   help="only verify an existing install and exit")
    p.add_argument("--dry-run", action="store_true",
                   help="print what would happen; change nothing")
    p.add_argument("-v", "--verbose", action="store_true")
    return p.parse_args(argv)


def main(argv: list[str]) -> int:
    global VERBOSE, DRY_RUN
    args = parse_args(argv)
    VERBOSE = args.verbose
    DRY_RUN = args.dry_run
    _init_console()

    # --check and --dry-run only read; everything else needs root/admin
    if not DRY_RUN and not args.check:
        require_privileges(argv)

    s = gather_settings(args)
    stack = build_stack(s)

    step(f"Locating the existing stack ({stack.label})")
    stack.detect()
    info(f"apache : {stack.apache.binary or 'not found'}")
    info(f"php    : {stack.php.binary or 'not found'}"
         f"{' (' + stack.php.version + ')' if stack.php.version else ''}")
    info(f"php mod: {stack.php.apache_module or stack.php.fpm_service or 'not found'}")
    info(f"mysql  : {stack.mysql.client or 'not found'}")

    if args.check:
        admin = MySQLAdmin(stack.mysql.client, s.mysql_root_pass, allow_sudo=True) \
            if stack.mysql.client else None
        checked = verify(s, stack)
        summary(s, stack, admin, checked)
        return 0 if checked else 1

    if s.install_packages:
        stack.install()
    else:
        info("--skip-install: using what is already installed")

    step("Preparing WaSQL directories")
    wasql_filesystem(s, stack)

    step("Writing config.xml")
    wasql_config_xml(s)

    step("Configuring PHP")
    stack.php_write_ini()

    configure_apache(s, stack)

    if isinstance(stack, LinuxStack):
        stack.selinux_fixup()

    step("Starting MySQL")
    r = stack.mysql_start()
    if r.good:
        ok("MySQL is running")
    else:
        warn(f"MySQL may not be running: {r.text.splitlines()[:2]}")

    step("Creating the WaSQL database and user")
    if not stack.mysql.client:
        warn("no mysql client found; skipping database setup")
        admin = MySQLAdmin(Path("mysql"), s.mysql_root_pass, allow_sudo=True)
    else:
        admin = MySQLAdmin(stack.mysql.client, s.mysql_root_pass, allow_sudo=True)
        if setup_database(s, admin):
            tune_mysql(s, admin, stack)

    step("Starting Apache")
    if s.port != 80 and port_in_use(s.port):
        info(f"port {s.port} is already answering - it will be taken over/reused")
    r = stack.apache_restart()
    if r.good:
        ok("Apache restarted")
    else:
        warn("Apache did not start cleanly:\n" +
             "\n".join(r.text.splitlines()[-10:]))

    checked = verify(s, stack)
    if checked:
        install_sample_site(s, admin)

    summary(s, stack, admin, checked)
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    except KeyboardInterrupt:
        print()
        die("interrupted", 130)
