#!/usr/bin/env python3
"""
install_localhost.py - install and configure a complete local WaSQL stack.

Installs (or reuses) Apache, PHP and MySQL on Windows, Linux or macOS, wires
them together for WaSQL, creates the WaSQL database/user, writes config.xml, and
optionally runs the WaSQL setup wizard so you end up with a working site at
http://localhost/ and the admin interface at http://localhost/php/admin.php
(default login admin/admin).

Design goals
  * hands off - every question is asked up front, then it runs unattended.
  * -y / --yes runs with defaults and asks nothing at all.
  * idempotent - safe to re-run; generated blocks are sentinel-marked and
    existing files are backed up before being touched.
  * never clobbers an existing config.xml (it reads the db settings out of it
    instead, unless you pass --force-config).

Typical use
  Windows (from an *elevated* PowerShell / cmd):
      python install_localhost.py
  Linux / macOS:
      python3 install_localhost.py          # re-execs itself under sudo
  Fully unattended:
      python3 install_localhost.py --yes --sample wacss

Run with --help for all options, or --check to only verify an existing install.
"""

