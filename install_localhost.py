def is_admin() -> bool:
    if IS_WIN:
        try:
            return bool(ctypes.windll.shell32.IsUserAnAdmin())
        except Exception:
            return False
    return os.geteuid() == 0


def require_privileges(argv: list[str]):
    """Windows: demand an elevated shell. POSIX: re-exec through sudo."""
    if is_admin():
        return
    if IS_WIN:
        die("this installer must run elevated.\n"
            "  Right-click 'Windows PowerShell' (or Terminal) -> Run as "
            "administrator, then re-run:\n"
            f"      python {' '.join([Path(sys.argv[0]).name] + argv)}")
    sudo = which("sudo")
    if not sudo:
        die("root privileges are required and sudo was not found. "
            "Re-run this script as root.")
    print(f"{C.YELLOW}Re-running under sudo (you may be asked for your "
          f"password)...{C.OFF}")
    cmd = [str(sudo), "-E", sys.executable, os.path.abspath(sys.argv[0])] + argv
    os.execv(str(sudo), cmd)  # replaces this process


def invoking_user() -> Optional[str]:
    """The human behind a sudo invocation (needed for Homebrew)."""
    u = os.environ.get("SUDO_USER")
    if u and u != "root":
        return u
    return None


