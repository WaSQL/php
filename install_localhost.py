@dataclass
class Result:
    code: int
    out: str
    err: str

    @property
    def good(self) -> bool:
        return self.code == 0

    @property
    def text(self) -> str:
        return (self.out + "\n" + self.err).strip()


def run(cmd: Sequence[str] | str, check: bool = False, timeout: int = 1800,
        env: Optional[dict] = None, cwd: Optional[str | Path] = None,
        stdin_text: Optional[str] = None, quiet: bool = False,
        allow_dry: bool = True) -> Result:
    """Run a command and capture output. Never raises unless check=True."""
    shell = isinstance(cmd, str)
    shown = cmd if shell else " ".join(str(c) for c in cmd)
    if DRY_RUN and allow_dry:
        info(f"{C.DIM}[dry-run] {shown}{C.OFF}")
        return Result(0, "", "")
    debug(f"$ {shown}")
    full_env = dict(os.environ)
    if env:
        full_env.update(env)
    try:
        p = subprocess.run(
            cmd if shell else [str(c) for c in cmd],
            shell=shell, capture_output=True, text=True, timeout=timeout,
            env=full_env, cwd=str(cwd) if cwd else None, input=stdin_text,
            errors="replace",
        )
        res = Result(p.returncode, (p.stdout or "").strip(), (p.stderr or "").strip())
    except FileNotFoundError as e:
        res = Result(127, "", str(e))
    except subprocess.TimeoutExpired:
        res = Result(124, "", f"timed out after {timeout}s")
    if VERBOSE and res.text:
        for line in res.text.splitlines()[:40]:
            debug(f"| {line}")
    if not res.good and not quiet:
        debug(f"exit {res.code}: {shown}")
    if check and not res.good:
        die(f"command failed ({res.code}): {shown}\n{res.text}")
    return res


def powershell(script: str, check: bool = False, timeout: int = 1800,
               allow_dry: bool = True) -> Result:
    return run(["powershell.exe", "-NoProfile", "-NonInteractive",
                "-ExecutionPolicy", "Bypass", "-Command", script],
               check=check, timeout=timeout, allow_dry=allow_dry)


def which(*names: str) -> Optional[Path]:
    for n in names:
        p = shutil.which(n)
        if p:
            return Path(p)
    return None


def first_existing(*candidates: str | Path | None) -> Optional[Path]:
    for c in candidates:
        if not c:
            continue
        for hit in sorted(glob.glob(str(c)), reverse=True):
            p = Path(hit)
            if p.exists():
                return p
    return None


def port_in_use(port: int, host: str = "127.0.0.1") -> bool:
    with socket.socket() as s:
        s.settimeout(1.0)
        return s.connect_ex((host, port)) == 0


